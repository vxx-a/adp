"""Generate the shipped skill catalog from its canonical skill metadata."""

import argparse
from pathlib import Path
import re
import sys


REPO = Path(__file__).resolve().parents[1]
SKILLS = REPO / "template/.agents/skills"
OUTPUT = REPO / "template/.agents/adp/skills.md"


def metadata(path):
    text = path.read_text(encoding="utf-8")
    match = re.match(r"\A---\n(.*?)\n---\n(.+)\Z", text, re.S)
    if not match:
        raise ValueError(f"{path}: missing frontmatter or body")
    fields = {}
    for line in match[1].splitlines():
        field = re.fullmatch(r"(name|description): ([^\n]+)", line)
        if not field or field[1] in fields:
            raise ValueError(f"{path}: expected unique plain name and description fields")
        fields[field[1]] = field[2]
    name = fields.get("name", "")
    description = fields.get("description", "")
    if name != path.parent.name or not re.fullmatch(r"adp-[a-z0-9]+(?:-[a-z0-9]+)*", name) or len(name) >= 64:
        raise ValueError(f"{path}: name must match its adp- skill folder and be shorter than 64 characters")
    if not description or len(description) > 1024 or any(char in description for char in "\n<>|[]"):
        raise ValueError(f"{path}: invalid catalog description")
    if not re.match(r"[A-Za-z]", description) or re.search(r":(?:\s|$)|\s#", description) or description.lower() in {"true", "false", "null", "yes", "no", "on", "off"}:
        raise ValueError(f"{path}: description must be a plain YAML string without mapping or comment syntax")
    if re.search(r"\b(?:TODO|FIXME|PLACEHOLDER)\b", match[2]):
        raise ValueError(f"{path}: unfinished scaffold")
    return name, description


def render(directory=SKILLS):
    folders = sorted(directory.glob("adp-*"))
    if not folders:
        raise ValueError("no shipped skills found")
    rows = ["# ADP skills", "", "Generated by `python3 scripts/build_catalog.py`; edit skill metadata, then regenerate.", "", "| Skill | When to use |", "|---|---|"]
    for folder in folders:
        path = folder / "SKILL.md"
        if folder.is_symlink() or not folder.is_dir() or path.is_symlink() or not path.is_file():
            raise ValueError(f"{folder}: skill must be a directory containing a regular SKILL.md")
        name, description = metadata(path)
        rows.append(f"| [{name}](../skills/{name}/SKILL.md) | {description} |")
    return "\n".join(rows) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the catalog differs; never write")
    args = parser.parse_args()
    try:
        expected = render()
        if args.check:
            if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
                raise ValueError("skill catalog is stale; run python3 scripts/build_catalog.py")
            print("Skill metadata and generated catalog passed.")
        else:
            OUTPUT.write_text(expected, encoding="utf-8")
            print(f"Generated {OUTPUT.relative_to(REPO)}")
        return 0
    except (ValueError, OSError, UnicodeError) as error:
        print(error, file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
